/**
 * Builds a release APK that installs directly on an Android phone.
 *
 *   node scripts/build-release-apk.mjs --api-url https://your-name.ngrok-free.dev
 *   node scripts/build-release-apk.mjs          (uses RELEASE_API_URL from mobile/.env)
 *
 * Run from mobile/ (or `npm run build:release-apk -- --api-url <url>`).
 *
 * Why this exists. The development build (`expo run:android`) is for the
 * emulator only: it contains one CPU architecture (x86_64), no JavaScript
 * (it loads that from Metro) and the emulator's backend address. A phone needs
 * a *release* build, which bundles the JavaScript and includes the phone's
 * architecture (arm64-v8a). Three details made this fail by hand, so the
 * script handles them:
 *
 *   1. EXPO_PUBLIC_API_URL is baked into the JavaScript bundle at build time.
 *      Gradle does not treat an environment variable as an input, so after the
 *      first build it re-uses the old bundle ("UP-TO-DATE") and the APK keeps
 *      the old address. The script forces the bundle task to re-run, then
 *      checks the finished bundle really contains the address you passed.
 *   2. Release builds block plain http:// traffic; only the debug manifest
 *      allows it. An https:// address (ngrok, a hosted server) needs nothing.
 *      For an http:// address (a LAN IP) the script allows cleartext traffic in
 *      the generated manifest, and removes that allowance again for https.
 *   3. mobile/android/ is generated by `expo prebuild` and git-ignored, so
 *      the script creates it when it is missing instead of assuming it is there.
 *
 * Release builds are signed with the debug keystore that Expo generates. That
 * installs fine by hand and keeps the Firebase fingerprint the same as the dev
 * build, but it is not a Play Store signature.
 *
 * Needs JDK 17 to 21 (JAVA_HOME) and the Android SDK, the same as the dev build.
 */
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const mobileDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const androidDir = join(mobileDir, "android");
const manifestPath = join(androidDir, "app", "src", "main", "AndroidManifest.xml");
const bundlePath = join(androidDir, "app", "build", "generated", "assets", "react", "release", "index.android.bundle");
const apkPath = join(androidDir, "app", "build", "outputs", "apk", "release", "app-release.apk");

/** Reads `--name value` from the command line, or returns the fallback. */
function option(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}

// The address comes from --api-url, or else RELEASE_API_URL in mobile/.env (git-ignored). It is a separate
// variable from EXPO_PUBLIC_API_URL on purpose: that one is what `expo start` uses for the emulator, and
// pointing it at a public address would send emulator traffic through the internet.
// loadEnvFile never overrides a variable already set in the shell.
if (existsSync(join(mobileDir, ".env"))) process.loadEnvFile(join(mobileDir, ".env"));
const apiUrl = option("api-url", process.env.RELEASE_API_URL);
// arm64-v8a is every modern phone; x86_64 keeps the same APK usable on emulators.
const abis = option("abis", "arm64-v8a,x86_64");
const outDir = resolve(mobileDir, option("out", "dist"));

if (!apiUrl) {
  console.error("Missing backend address. Pass --api-url https://<your-host>, or set RELEASE_API_URL in mobile/.env.");
  process.exit(1);
}
if (!/^[a-z0-9_,-]+$/.test(abis)) {
  console.error(`--abis must be a comma-separated list such as arm64-v8a,x86_64. Got: ${abis}`);
  process.exit(1);
}
if (!/^https?:\/\/[^/\s]+$/.test(apiUrl)) {
  console.error(`--api-url must look like https://host or http://host:3000, with no path. Got: ${apiUrl}`);
  process.exit(1);
}
if (/\/\/(localhost|127\.0\.0\.1|10\.0\.2\.2)\b/.test(apiUrl)) {
  console.error(`${apiUrl} only works inside the emulator or on this computer. A phone cannot reach it. Use a LAN IP or a public address.`);
  process.exit(1);
}

/** Runs a command in the given folder, streaming its output; exits the script if it fails. */
function run(command, args, cwd) {
  console.log(`\n> ${command} ${args.join(" ")}`);
  // shell:true is needed on Windows for .bat files and npx. Every argument is a fixed string or was
  // validated above (--abis); the backend address travels in the environment, never on the command line.
  const result = spawnSync([command, ...args].join(" "), { cwd, stdio: "inherit", shell: true, env: { ...process.env, EXPO_PUBLIC_API_URL: apiUrl, NODE_ENV: "production" } });
  if (result.status !== 0) {
    console.error(`\nFailed: ${command} ${args.join(" ")}`);
    process.exit(result.status ?? 1);
  }
}

// 1. The native project is generated, so create it if this is a fresh clone.
if (!existsSync(androidDir)) {
  run("npx", ["expo", "prebuild", "--platform", "android", "--no-install"], mobileDir);
}

// 2. Make the generated manifest match the address: cleartext only for http://.
const manifest = readFileSync(manifestPath, "utf8");
const flag = ' android:usesCleartextTraffic="true"';
const wantsCleartext = apiUrl.startsWith("http://");
const withoutFlag = manifest.replace(flag, "");
const patched = wantsCleartext ? withoutFlag.replace("<application", `<application${flag}`) : withoutFlag;
if (patched !== manifest) {
  writeFileSync(manifestPath, patched);
  console.log(wantsCleartext ? "Allowed cleartext (http) traffic in the generated manifest." : "Removed the cleartext allowance; the address is https.");
}

// 3. Build. `--rerun` applies to the task named just before it, forcing a fresh
// JavaScript bundle so the address above is baked in (see the header, point 1).
// Explicit ".\" / "./": Windows' cmd does not look in the working folder for a bare name.
const gradle = process.platform === "win32" ? ".\\gradlew.bat" : "./gradlew";
run(gradle, [":app:createBundleReleaseJsAndAssets", "--rerun", "assembleRelease", `-PreactNativeArchitectures=${abis}`, "--console=plain"], androidDir);

// 4. Prove the address made it into the bundle, instead of trusting the build.
if (!readFileSync(bundlePath).includes(Buffer.from(apiUrl))) {
  console.error(`\nThe finished bundle does not contain ${apiUrl}. The APK would call the wrong server; not copying it.`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, "YouthLink-release.apk");
copyFileSync(apkPath, outFile);
const sha256 = createHash("sha256").update(readFileSync(outFile)).digest("hex").toUpperCase();

console.log(`\nBuilt ${outFile}`);
console.log(`  backend address in the bundle: ${apiUrl}`);
console.log(`  architectures:                 ${abis}`);
console.log(`  SHA-256:                       ${sha256}`);
